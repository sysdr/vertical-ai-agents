#!/bin/bash
# Script to remove frontend/node_modules directory
# This requires sudo as the directory is owned by root

echo "Removing frontend/node_modules directory..."
echo "This requires sudo privileges..."

if [ -d "l19-naive-rag/frontend/node_modules" ]; then
    sudo rm -rf l19-naive-rag/frontend/node_modules
    if [ $? -eq 0 ]; then
        echo "✓ Successfully removed l19-naive-rag/frontend/node_modules"
    else
        echo "✗ Failed to remove directory"
        exit 1
    fi
elif [ -d "frontend/node_modules" ]; then
    sudo rm -rf frontend/node_modules
    if [ $? -eq 0 ]; then
        echo "✓ Successfully removed frontend/node_modules"
    else
        echo "✗ Failed to remove directory"
        exit 1
    fi
else
    echo "✓ node_modules directory not found (already removed)"
fi
